/**
 * Pure black for OLED screens: the page is #000 and the tonal containers are pulled most of
 * the way to black, keeping just enough separation for grouped cards to read.
 */
internal fun ColorScheme.toPureBlack(): ColorScheme = copy(
    background = Color.Black,
    surface = Color.Black,
    surfaceDim = Color.Black,
    surfaceContainerLowest = Color.Black,
    surfaceContainerLow = lerp(Color.Black, surfaceContainerLow, 0.6f),
    surfaceContainer = lerp(Color.Black, surfaceContainer, 0.7f),
    surfaceContainerHigh = lerp(Color.Black, surfaceContainerHigh, 0.8f),
    surfaceContainerHighest = lerp(Color.Black, surfaceContainerHighest, 0.9f),
    surfaceBright = surfaceContainerHigh,
)

